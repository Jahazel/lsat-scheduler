#!/usr/bin/env node
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { writeFileSync } from "node:fs";
import { dirname, resolve, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../../..");
const directory = process.argv[2];
if (!directory || process.argv.length !== 3) throw new Error("Usage: smoke.mjs .verification/evidence/<run-name>");
const run = resolve(root, directory);
const base = resolve(root, ".verification/evidence");
if (!relative(base, run) || relative(base, run).startsWith("..")) throw new Error("Use a directory below .verification/evidence/.");
const helper = resolve(root, ".claude/skills/verify/scripts/local.mjs");
const check = (command) => JSON.parse(execFileSync(process.execPath, [helper, command, directory], { cwd: root, encoding: "utf8" }));
const healthy = check("doctor");
const modulePath = process.env.VERIFY_PLAYWRIGHT_MODULE || resolve(run, "scratch/tools/node_modules/playwright/index.mjs");
const { chromium } = await import(pathToFileURL(modulePath).href);
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, recordVideo: { dir: resolve(run, "video") } });
const page = await context.newPage();
const actions = [];
const errors = [];
const email = "verify-smoke@example.test";
const password = randomBytes(18).toString("base64url") + "Aa1";
const save = (name, value) => writeFileSync(resolve(run, name), JSON.stringify(value, null, 2) + "\n");
const records = (name) => { const value = check("inspect"); save(name, value); return value; };
const log = (action) => actions.push({ at: new Date().toISOString(), action, url: page.url() });
const heading = (name) => page.getByRole("heading", { name, exact: true }).waitFor();
const goto = async (path) => { log(`Navigate to ${path}`); await page.goto(healthy.url + path); };
async function capture(name) {
  await page.screenshot({ path: resolve(run, `${name}.png`), fullPage: true });
  writeFileSync(resolve(run, `${name}.aria.txt`), await page.locator("body").ariaSnapshot());
}
page.on("pageerror", (error) => errors.push(error.message));
await context.tracing.start({ screenshots: true, snapshots: true, sources: true });
try {
  save("doctor.json", healthy);
  const initial = records("records-before.json");
  assert.equal(initial.users.length, 0, "Smoke requires an empty disposable database.");
  await goto("/");
  await capture("landing");
  log("Choose Build my first plan");
  await page.getByRole("link", { name: "Build my first plan", exact: true }).click();
  await heading("Create your account");
  await goto("/");
  log("Choose the public Sign up navigation link");
  await page.locator("header").getByRole("link", { name: "Sign up", exact: true }).click();
  await heading("Create your account");
  log("Choose the signup form's Log in link");
  await page.locator("main").getByRole("link", { name: "Log in", exact: true }).click();
  await heading("Log in");
  log("Choose the login form's Sign up link");
  await page.locator("main").getByRole("link", { name: "Sign up", exact: true }).click();
  await heading("Create your account");
  await goto("/");
  log("Choose the public Log in navigation link");
  await page.locator("header").getByRole("link", { name: "Log in", exact: true }).click();
  await heading("Log in");
  await goto("/signup");
  await page.locator('input[name="name"]').fill("Verify Student");
  await page.locator('input[name="email"]').fill(email);
  await page.locator('input[name="password"]').fill(password);
  log("Submit valid signup fields without consent");
  await page.getByRole("button", { name: "Sign up", exact: true }).click();
  assert(await page.locator('input[name="agreedToTerms"]').evaluate((input) => input.validity.valueMissing));
  assert.equal(records("records-consent-refused.json").users.length, 0);
  await capture("consent-refused");
  log("Accept terms and create the Account");
  await page.locator('input[name="agreedToTerms"]').check();
  await page.getByRole("button", { name: "Sign up", exact: true }).click();
  await heading("Tell us about your prep");
  const signedUp = records("records-signup.json");
  assert.equal(signedUp.users.length, 1);
  assert.equal(signedUp.users[0].email, email);
  assert.equal(signedUp.users[0].role, "student");
  assert.equal(signedUp.students.length, 0);
  await page.reload();
  await heading("Tell us about your prep");
  log("Choose Saturday and June 2027 and submit onboarding without a screenshot");
  await page.locator('main label:has-text("Preferred practice-test day") select').selectOption("SATURDAY");
  await page.locator('main label:has-text("Goal test date") select').selectOption("2027-06-01");
  await capture("onboarding-before-save");
  await page.getByRole("button", { name: "Generate my schedule", exact: true }).click();
  await heading("Add your latest analytics snapshot");
  const onboarded = records("records-onboarding.json");
  assert.equal(onboarded.students.length, 1);
  assert.equal(onboarded.students[0].goalScore, 165);
  assert.equal(onboarded.students[0].preferredPracticeTestDay, "SATURDAY");
  assert.equal(onboarded.students[0].goalTestDate, "2027-06-01");
  assert.deepEqual(Object.values(onboarded.students[0].dailyCapacityMinutes), Array(7).fill(90));
  assert.equal(onboarded.weeklyschedules.length, 0);
  log("Open Study settings through navigation");
  await page.getByRole("link", { name: "Study settings", exact: true }).click();
  await heading("Study settings");
  await page.getByRole("spinbutton", { name: "Goal score", exact: true }).fill("168");
  await page.getByRole("combobox", { name: "All days hours", exact: true }).selectOption("0");
  await page.getByRole("button", { name: "Apply", exact: true }).click();
  log("Set goal score 168, apply 30 minutes to all days, and save");
  await capture("settings-before-save");
  await page.getByRole("button", { name: "Save changes", exact: true }).click();
  await heading("Add your latest analytics snapshot");
  await goto("/settings");
  await heading("Study settings");
  assert.equal(await page.getByRole("spinbutton", { name: "Goal score", exact: true }).inputValue(), "168");
  for (const day of ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"]) {
    assert.equal(await page.getByRole("combobox", { name: `${day} hours`, exact: true }).inputValue(), "0");
    assert.equal(await page.getByRole("combobox", { name: `${day} minutes`, exact: true }).inputValue(), "30");
  }
  const updated = records("records-settings.json");
  assert.equal(updated.students[0].goalScore, 168);
  assert.deepEqual(Object.values(updated.students[0].dailyCapacityMinutes), Array(7).fill(30));
  await capture("settings-reopened");
  log("Open Account through its menu");
  await page.getByRole("button", { name: `Account menu for ${email}`, exact: true }).click();
  await page.getByRole("menuitem", { name: "Account", exact: true }).click();
  await heading("Account");
  await capture("account");
  log("Log out and request protected Account directly");
  await page.getByRole("button", { name: `Account menu for ${email}`, exact: true }).click();
  await page.getByRole("menuitem", { name: "Log out", exact: true }).click();
  await page.waitForURL(healthy.url + "/");
  await goto("/account");
  await heading("Log in");
  await page.locator('input[name="email"]').fill(email);
  await page.locator('input[name="password"]').fill("WrongPassword123");
  log("Submit an invalid password");
  await page.getByRole("button", { name: "Log in", exact: true }).click();
  await page.getByText("Invalid email or password.", { exact: true }).waitFor();
  await capture("invalid-login");
  log("Submit the valid password");
  await page.locator('input[name="email"]').fill(email);
  await page.locator('input[name="password"]').fill(password);
  await page.getByRole("button", { name: "Log in", exact: true }).click();
  await heading("Add your latest analytics snapshot");
  for (const path of ["/login", "/signup"]) {
    await goto(path);
    assert.equal(new URL(page.url()).pathname, "/dashboard");
  }
  await goto("/account");
  await heading("Account");
  await page.locator('input[name="confirmation"]').fill("DELETE");
  log("Delete the disposable student's Account");
  await page.getByRole("button", { name: "Delete account", exact: true }).click();
  await page.getByRole("link", { name: "Build my first plan", exact: true }).waitFor();
  const deleted = records("records-deleted.json");
  for (const collection of ["users", "students", "analyticssnapshots", "weeklyschedules", "activitycheckins"]) assert.equal(deleted[collection].length, 0);
  await goto("/login");
  await page.locator('input[name="email"]').fill(email);
  await page.locator('input[name="password"]').fill(password);
  log("Try the deleted Account's valid password");
  await page.getByRole("button", { name: "Log in", exact: true }).click();
  await page.getByText("Invalid email or password.", { exact: true }).waitFor();
  await capture("deleted-account-login");
  assert.deepEqual(errors, []);
  save("smoke-result.json", { passed: true, areas: ["sign-up-account", "study-settings"], pageErrors: errors, limitations: ["No nonempty analytics or schedule history in the deletion fixture", "No capacity-notice settings entry, mobile navigation, Google sign-in, or screenshot extraction"] });
  console.log(`Passed signup, onboarding, settings persistence, sign-in, sign-out, and Account deletion. Evidence: ${run}`);
} catch (error) {
  await capture("failure").catch(() => {});
  save("smoke-result.json", { passed: false, error: error.message, pageErrors: errors });
  throw error;
} finally {
  save("actions.json", actions);
  await context.tracing.stop({ path: resolve(run, "trace.zip") });
  await context.close();
  await browser.close();
}
